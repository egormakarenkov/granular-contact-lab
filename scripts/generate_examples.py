"""Regenerate every shipped recording from synthetic initial conditions.

Run from the repository root: python scripts/generate_examples.py
No imported experiment, external dataset, or AI service is used.
"""
from dataclasses import asdict, replace
import gzip
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import numpy as np
import scipy
import osqp
from granular.physics import Settings, State, advance, force_range, prepare, simulate


def write_json(path, data):
    path.write_text(json.dumps(data, indent=2, allow_nan=False), encoding='utf-8')


def save_run(run, label):
    run['initial_hash'] = hashlib.sha256(json.dumps(run['initial'], sort_keys=True).encode()).hexdigest()[:16]
    run['id'] = hashlib.sha256(json.dumps({'settings': run['settings'], 'initial': run['initial']}, sort_keys=True).encode()).hexdigest()[:12]
    run['created'] = 0  # Fixture, not a person's activity timestamp.
    run['label'] = label
    run['provenance'] = 'Synthetic fixture generated by scripts/generate_examples.py'
    run['versions'] = {'python': sys.version.split()[0], 'numpy': np.__version__, 'scipy': scipy.__version__, 'osqp': osqp.__version__}
    (ROOT/'examples'/'runs'/f"{run['id']}.json.gz").write_bytes(gzip.compress(json.dumps(run, allow_nan=False).encode(), mtime=0))
    return {'id': run['id'], 'label': label, 'settings': run['settings'], 'initial_hash': run['initial_hash'], 'metrics': run['metrics']}


def main():
    folder = ROOT/'examples'
    (folder/'runs').mkdir(parents=True, exist_ok=True)
    # Analytic support benchmark. Reference grain mass is (r/.12)^2.
    st = State(np.array([[1., .1]]), np.array([.1]), np.zeros((1, 2)))
    c = Settings(particles=1, waveform='hold', intruder_y=4, duration=.12)
    _, diagnostic = advance(st, c, 0, .01)
    idx = next(i for i, z in enumerate(diagnostic['contacts']) if z['kind']=='floor')
    expected = (.1/.12)**2
    assert abs(diagnostic['contacts'][idx]['force']-expected)<1e-4
    write_json(folder/'floor-support.json', {'kind':'analytic synthetic benchmark', 'expected_reaction':expected,
        'computed_reaction':diagnostic['contacts'][idx]['force'], 'force_bounds':force_range(diagnostic,idx)})

    # Deliberately duplicated constraint: algebraic ambiguity, not two physical floors.
    z = {'i':0,'j':-1,'kind':'floor','normal':[0,1],'status':'loaded','slack':0}
    bounds = force_range({'contacts':[z.copy(),z.copy()], 'target_reaction':[0,1]},0)
    assert abs(bounds['min'])<1e-5 and abs(bounds['max']-1)<1e-4
    write_json(folder/'redundant-support.json', {'kind':'synthetic duplicated-constraint algebra example',
        'equation':'lambda_1 + lambda_2 = 1; lambda_i >= 0', 'expected_range':[0,1], 'computed_bounds':bounds})

    base = Settings(particles=36, seed=2027, duration=.6, dt=.015, waveform='translate', stroke=.03, amplitude=.02)
    entries, comparisons = [], []
    default = None
    for seed in (2027, 2028, 2029):
        c = replace(base, seed=seed)
        initial, _ = prepare(c)
        if seed==2027:write_json(folder/'default-packing.json', initial.json())
        pair = []
        for name, cc in [('Translation',c),('Lateral sway',replace(c,waveform='sway'))]:
            run = simulate(cc,initial)
            entry = save_run(run,f'{name} · synthetic seed {seed}')
            entries.append(entry); pair.append(entry)
            if seed==2027 and name=='Lateral sway':default=run
        assert pair[0]['initial_hash']==pair[1]['initial_hash']
        comparisons.append({'seed':seed,'runs':pair})
        print(f'Synthetic seed {seed} complete',flush=True)
        if seed==2027:
            fine = []
            for cc in (replace(c,dt=c.dt/2),replace(c,waveform='sway',dt=c.dt/2)):
                entry=save_run(simulate(cc,initial),f'Half timestep · {cc.waveform} · synthetic seed {seed}')
                entries.append(entry);fine.append(entry)
            comparisons[-1]['half_timestep']=fine

    assert default is not None
    (folder/'default-run-id.txt').write_text(default['id'],encoding='utf-8')
    manifest = {'provenance':'Fresh synthetic examples; deterministic generator and exact initial arrays supplied.',
        'seeds':[2027,2028,2029], 'default':default['id'], 'runs':entries, 'comparisons':comparisons,
        'interpretation':'Descriptive model outputs. No physical calibration, optimality claim or experimental data.'}
    write_json(folder/'manifest.json',manifest)
    # Compact recording retains only fields used by the offline viewer.
    recording = {k:default[k] for k in ('settings','initial','initial_hash','metrics','r','versions')}
    recording['frames'] = [{k:f[k] for k in ('t','q','intruder','reaction','positive_work','penetration')}
                           | {'contacts':[{k:z[k] for k in ('i','j','kind','normal','gap','force')} for z in f['contacts'] if z['force']>1e-4]}
                           for f in default['frames']]
    def compact(x):
        if isinstance(x,float):return round(x,9)
        if isinstance(x,list):return [compact(v) for v in x]
        if isinstance(x,dict):return {k:compact(v) for k,v in x.items()}
        return x
    data=json.dumps(compact(recording),separators=(',',':'),allow_nan=False).replace('<','\\u003c')
    template=(ROOT/'demo'/'replay.template.html').read_text(encoding='utf-8')
    (ROOT/'demo'/'index.html').write_text(template.replace('__RECORDING__',data),encoding='utf-8')
    print(f'Generated {len(entries)} recordings and demo/index.html',flush=True)


if __name__=='__main__':main()
